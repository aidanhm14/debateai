import assert from 'node:assert/strict';
import fs from 'node:fs';
import { motionForPairArrival, draftConfigForPairMotion } from '../app/netlify/functions/lib/spar-motion-arrival.mjs';
import { createDraft } from '../app/netlify/functions/lib/motion-draft.mjs';
const motion='Cities should tax empty homes to fund public housing.';
const stamp={eligible:true,uids:['a','b'],motionGeneration:{status:'generated',motion}};
const a={room:'room-one',status:'consent',matchedWith:'b',motion:''};
const b={room:'room-one',status:'consent',matchedWith:'a',motion:''};
const arrive=(s=stamp,m=a,t=b,r='room-one')=>motionForPairArrival(s,m,t,r,'a','b');
assert.equal(arrive(),motion);
assert.equal(motionForPairArrival(stamp,b,a,'room-one','b','a'),motion,'both callers converge');
assert.equal(arrive({...stamp,motionGeneration:{status:'fallback',motion}}),motion);
for(const status of ['ready','running','failed',undefined]) assert.equal(arrive({...stamp,motionGeneration:{status,motion}}),null);
for(const status of ['matched','cancelled','waiting']){
 assert.equal(arrive(stamp,{...a,status}),null,'never alter a room after navigation');
 assert.equal(arrive(stamp,a,{...b,status}),null,'peer must still be accepting');
}
assert.equal(arrive(stamp,{...a,motion:'My explicit choice.'}),null);
assert.equal(arrive(stamp,a,{...b,motion:'Peer explicit choice.'}),null);
assert.equal(arrive(stamp,{...a,room:'next-room'}),null,'stale provider result cannot enter a rematch');
assert.equal(arrive(stamp,a,{...b,room:'next-room'}),null);
assert.equal(arrive(stamp,{...a,matchedWith:'c'}),null);
assert.equal(arrive(stamp,a,{...b,matchedWith:'c'}),null);
assert.equal(arrive({...stamp,uids:['a','c']}),null);
assert.equal(arrive({...stamp,eligible:false}),null);
assert.equal(arrive(null),null);
assert.equal(arrive({...stamp,motionGeneration:{status:'generated',motion:'x'.repeat(201)}}),null);
const config=draftConfigForPairMotion({suggestions:['Cities should build more housing.',motion]},motion);
assert.equal(config.suggestions.filter(t=>t===motion).length,1);
const draft=createDraft('room-one','casual','a','b',config);
assert.equal(draft.pool[0].text,motion);
assert.equal(draft.pool[0].recommended,true);
assert.equal(draft.poolLocked,false);
assert.equal(draft.motionId,null);
assert.equal(draft.side,null);
const source=fs.readFileSync(new URL('../app/netlify/functions/spar-pair.mjs',import.meta.url),'utf8');
const accept=source.slice(source.indexOf("if (action === 'consent')"),source.indexOf('// The queue-doc draft is GONE'));
assert.ok(accept.indexOf('await ensurePairMotion(')<accept.indexOf('const result = await db.runTransaction('),'provider call is outside retried transaction');
assert.match(accept,/preparedMotionRef \? tx.get\(preparedMotionRef\)/,'finalization reads durable result');
assert.match(accept,/finals.pairedMotion = generatedMotion/);
assert.match(accept,/tx.update\(myRef, \{\s*\.\.\.finals/);
assert.match(accept,/tx.update\(peerRef, \{\s*\.\.\.finals/,'same atomic motion reaches peer');
assert.ok(!accept.includes("collection('live_rounds')"),'generator never writes an active room');
assert.match(source,/mine.matchProfileReady === true && theirs.matchProfileReady === true\s*&& myMatchProfileSnap.exists && peerMatchProfileSnap.exists/,'both private profiles must have synced');
assert.match(source,/if \(!pairedMotion\) motionContext = buildMatchMotionContext/);
console.log('spar motion arrival: explicit motion, stale pair, simultaneous recipients and optional negotiation passed');
