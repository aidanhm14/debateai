import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import clock from '../app/netlify/functions/room-clock.mjs';
const ctx = { window: {} }; vm.createContext(ctx);
vm.runInContext(readFileSync('app/js/room-clock.js','utf8'), ctx);
const C = ctx.window.DBRoomClock;
const start = 1700000000000;
const timer = { startMs: start, updatedAtMs: start, state: 'running', speechIdx: 0 };
assert.equal(C.localStart(timer), start);
assert.equal((start + 90000 - C.localStart(timer))/1000, 90, 'Late audience arrival includes the first 90 seconds');
const skewed = {...timer, startMs: start+22000, updatedAtMs: start+22000, updatedAtServer: {seconds:start/1000}};
assert.equal(C.localStart(skewed), start, 'A publisher clock 22 seconds ahead is corrected using a server stamp');
assert.equal(C.localStart({...skewed}), start, 'Repeated snapshots do not reset the timer');
const resumed = {...skewed, startMs: start+122000, updatedAtMs:start+122000, updatedAtServer:{seconds:(start+100000)/1000},accumulatedMs:45000};
assert.equal(resumed.accumulatedMs + start+120000-C.localStart(resumed),65000,'Pause and resume preserve accumulated time');
const response = await clock(new Request('https://itsdebatable.com/api/room-clock'));
assert.equal(response.headers.get('cache-control'), 'no-store');
assert.ok(Math.abs((await response.json()).now-Date.now())<1000);
console.log('Room clock: late audience joins, skew, repeated snapshots, paused time and uncached server time passed.');
