import assert from 'node:assert/strict';
import { memoryFirestore } from './lib/memory-firestore.mjs';
import { admitVideoRequest, videoCapacity, videoRoomProperties } from '../app/netlify/functions/lib/video-capacity.mjs';
assert.deepEqual(videoCapacity({}), { hourlyAdmissions: 6000, maxParticipants: 200 });
assert.equal(videoCapacity({DAILY_ROOM_MAX_PARTICIPANTS:'550'}).maxParticipants,550);
assert.equal(videoCapacity({DAILY_ROOM_MAX_PARTICIPANTS:'garbage'}).maxParticipants,200);
assert.equal(videoRoomProperties({DAILY_ROOM_MAX_PARTICIPANTS:'550'}).enable_terse_logging,true);
assert.equal(videoRoomProperties({}).enable_hidden_participants,true);
const f=memoryFirestore();
const now=1_800_000_000_000;
const requests=await Promise.all(Array.from({length:600},(_,i)=>admitVideoRequest(f.db,'person-'+i,{now})));
assert.equal(requests.filter(r=>r.ok).length,600,'100 speakers and 500 viewers can arrive concurrently');
const again=await Promise.all(Array.from({length:600},(_,i)=>admitVideoRequest(f.db,'person-'+i,{now:now+30_000})));
assert.equal(again.filter(r=>r.ok).length,600,'a reconnect burst has admission headroom');
let results=await Promise.all(Array.from({length:20},()=>admitVideoRequest(f.db,'same-person',{now})));
assert.equal(results.filter(r=>r.ok).length,12,'simultaneous instances share the caller limit');
const low=memoryFirestore();
results=await Promise.all(Array.from({length:130},(_,i)=>admitVideoRequest(low.db,'limited-'+i,{now,hourlyCap:100})));
assert.equal(results.filter(r=>r.ok).length,100,'partitioned site budget admits exactly its total capacity');
assert.equal([...low.data].filter(([k])=>k.includes('/site:')).reduce((n,[,d])=>n+d.count,0),100);
assert.equal((await admitVideoRequest(low.db,'after-reset',{now:now+3_600_000,hourlyCap:100})).ok,true);
await assert.rejects(admitVideoRequest({collection:f.db.collection,runTransaction:async()=>{throw new Error('offline');}},'no-budget',{now}));
console.log('[test-video-capacity] 600 arrivals, 600 reconnects, shared caller limits, exact global ceiling and reset passed');
