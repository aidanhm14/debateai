import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source=fs.readFileSync(new URL('../app/js/round-bet.js',import.meta.url),'utf8');
const scope=vm.createContext({});
vm.runInContext(source.slice(source.indexOf('  function resultCopy('),source.indexOf('  function paintResult(')),scope);
const copy=scope.resultCopy;
const bet={pick:'pro',stake:50};
const market={status:'settled',verdict:'pro',poolPro:100,poolCon:200};
assert.match(copy(market,bet,true).title,/\+100 tokens/);
assert.match(copy(market,bet,true).detail,/received 150 tokens, including your original stake/);
assert.match(copy({...market,poolCon:0},bet,true).title,/50 tokens returned. No profit/);
assert.equal(copy({...market,verdict:'con'},bet,true).title,'Your bet lost.','the settled pool, not the local ballot, decides the bet');
assert.match(copy({...market,status:'open'},bet,true).title,/settling/);
assert.match(copy({...market,status:'voided'},bet,true).detail,/full stake was refunded/);
assert.match(copy(market,null,true).detail,/No bet placed/);
assert.doesNotMatch(copy(market,null,true).title,/tokens/);
assert.match(copy({...market,poolPro:150,poolCon:50},bet,true).detail,/received 66 tokens/,'fractional returns use the settlement floor');
const live=fs.readFileSync(new URL('../app/live-round.html',import.meta.url),'utf8');
assert.ok(live.includes('id="ballotBetSlot"'),'the result lives in the visible ballot, outside the hidden live betting panel');
console.log('Bet result: settled returns, net profit, rounding, no bet, pending, loss and refunds passed.');
